/** Build one full Concept from compact options. */
function mk(n, o) {
  const tier = tierFor(o.type, 'healthcare');
  const bucket = o.bucket || 'queue';
  const renderings = [o.text, ...(o.alts || [o.text, o.text])];
  let floor = null;
  if (bucket === 'queue') {
    if (tier === 'critical') floor = 'critical';
    else if (tier === 'high' && o.conf < 0.6) floor = 'high_low_conf';
    else if (tier === 'low' && o.conf < 0.6) floor = 'low_low_conf';
    else if (o.sample) floor = 'high_sample';
  }
  const c = {
    id: `c_${String(n).padStart(4, '0')}`,
    source: o.source,
    variants: o.variants || [],
    termType: o.type,
    tier,
    tierReason: tierReasonFor(o.type, 'healthcare'),
    frequency: o.freq,
    pages: pg(...o.pages),
    proposal: { text: o.text, reason: o.reason },
    renderings,
    confidence: o.conf,
    judgeChecks: { importedAgrees: null, siblingAgrees: null, styleFit: o.styleFit !== false, selfConsistent: new Set(renderings).size === 1 },
    judgeNote: o.note,
    imported: o.imp ? { text: o.imp, sourceName: IMPORT_SOURCE } : null,
    sibling: o.sib ? { locale: 'es-MX', text: o.sib } : null,
    context: o.ctx,
    enforcement: defaultEnforcement(tier),
    scope: o.scope || (tier === 'critical' ? 'legal_safety' : o.type === 'marketing' ? 'marketing' : 'all'),
    bucket,
    floor,
    reopened: false,
    status: 'pending',
    decision: null,
  };
  if (c.imported) c.judgeChecks.importedAgrees = !importDisagrees(c);
  if (c.sibling) c.judgeChecks.siblingAgrees = normalizeTerm(c.sibling.text) === normalizeTerm(c.proposal.text);
  return c;
}

