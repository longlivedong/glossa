/** A preview item; `found` is computed with the same check the app uses. */
function pv(source, translation, terms, firstAttempt = null) {
  const entries = terms.map((s) => {
    const c = byTerm(s);
    return { conceptId: c.id, source: c.source, expected: c.proposal.text, mode: c.enforcement };
  });
  return { source, translation, terms: checkTerms(translation, entries), retried: !!firstAttempt, firstAttempt };
}

